"""Pass 2 — fine-grained boundary detection inside the padded candidate
windows only (~20% of the clip), at full frame rate.

Per window: full-rate player tracking, full-rate ball tracking (TrackNet if
weights are installed, otherwise the honest classical fallback), Kalman
smoothing, 3D height reconstruction, bounce/hit events, then the rally
start/end terminal-event logic. Per-frame feature traces are embedded in
the pass2 overlay entries — they double as training data for the learned
Pass 1 gate and bounce model later.
"""
from __future__ import annotations

import logging
import math

import numpy as np

from .. import db
from ..jobs import JobHandle
from . import overlays
from . import court
from .ball_coarse import MotionBallDetector
from .ball_tracknet import TrackNetBall
from .bounce import detect_events, reconstruct_world
from .court import CameraModel
from .kalman import smooth_track
from .players import PoseTracker, is_serve_formation
from .rally_logic import RallyDecision, detect_rallies
from .video_io import iter_frames, probe

log = logging.getLogger("cv.pass2")

# Bump whenever the detection logic that produces raw boundaries changes, so
# the validation harness only trusts stored raw_start/raw_end that were
# generated by the current code (else it re-runs Pass 2 first).
DETECTION_CODE_VERSION = 1


def _in_court_region(H, x: float, y: float, mx: float = 2.5, my: float = 3.0) -> bool:
    """Reject ball blobs whose court-plane projection is well outside THIS court
    — neighbouring courts and spectators are several metres beyond the generous
    margins here, while airborne / just-out balls stay within. Pass 1 masks the
    court region; Pass 2 previously did not, so once the player-box exclusion
    removed the shoe blobs, the detector latched onto neighbouring-court motion
    and produced a flood of phantom 'bounce OUT' events."""
    cxy = court.img_to_court(H, np.array([[float(x), float(y)]], dtype=np.float64))[0]
    return (-mx <= cxy[0] <= court.COURT_W + mx) and (-my <= cxy[1] <= court.COURT_L + my)


def _pick_candidate(cands, last_xy, max_jump: float):
    """Associate the classical detector's blobs with the ongoing track."""
    if not cands:
        return None
    if last_xy is None:
        return cands[0]
    best, best_d = None, max_jump
    for c in cands:
        d = math.hypot(c.x - last_xy[0], c.y - last_xy[1])
        if d < best_d:
            best, best_d = c, d
    return best or (cands[0] if last_xy is None else None)


def run_pass2(video_id: str, params: dict, H, cam: CameraModel | None,
              handle: JobHandle, source: str = "pass2",
              p1_source: str = "pass1") -> list[dict]:
    if H is None or cam is None:
        raise RuntimeError(
            "Pass 2 needs a court calibration (homography). Calibrate the "
            "court corners in the labeling tab, then hit Reprocess.")

    with db.connect() as con:
        vrow = con.execute("SELECT * FROM videos WHERE id=?", (video_id,)).fetchone()
        p1 = con.execute(
            "SELECT start_frame, end_frame FROM rally_labels"
            " WHERE video_id=? AND source=? ORDER BY start_frame",
            (video_id, p1_source),
        ).fetchall()
    path = vrow["path"]
    meta = probe(path)
    fps = meta.fps
    pad = int(params["p1_pad_s"] * fps)
    merge_gap = int(params["p1_merge_gap_s"] * fps)
    last_frame = meta.frame_count - 1

    # 1. Merge adjacent Pass 1 windows only when the RAW gap between them is
    #    small. Padding is applied AFTER merging (step 2), so a wide pad can no
    #    longer bridge two genuinely separate rallies into one window (the bug
    #    that made Pass 2 emit one rally where there were two).
    raw: list[list[int]] = []
    for r in p1:
        s, e = r["start_frame"], r["end_frame"]
        if raw and s - raw[-1][1] <= merge_gap:
            raw[-1][1] = max(raw[-1][1], e)
        else:
            raw.append([s, e])

    # 2. Pad each merged window, clamping the pad to at most half the gap to
    #    each neighbour so two padded windows can never overlap or re-bridge.
    #    Carry the raw (unpadded) bounds through: they give an honest boundary
    #    fallback and feed the validation harness (analytic offset re-eval).
    windows: list[tuple[int, int, int, int]] = []  # ws, we, raw_start, raw_end
    for i, (s, e) in enumerate(raw):
        left_gap = s - raw[i - 1][1] if i > 0 else 10**9
        right_gap = raw[i + 1][0] - e if i < len(raw) - 1 else 10**9
        ws = max(0, s - min(pad, max(0, left_gap // 2)))
        we = min(last_frame, e + min(pad, max(0, right_gap // 2)))
        windows.append((ws, we, s, e))

    tracknet = TrackNetBall()
    # Live trained start/end models (loaded once). None -> the heuristic runs;
    # a promoted model -> it drives event/boundary detection (blended with the
    # geometry safety guards). This is what makes the trained models actually
    # used by Pass 2 (previously load_bounce_model was defined but never called).
    from ..learning import model_registry
    models = model_registry.load_live_bundle()
    if source == "pass2":  # record which live model versions this real run used
        live = {k: (model_registry.latest_live(k) or (None,))[0]
                for k in ("rally_end", "serve_start")}
        with db.connect() as con:
            con.execute("UPDATE videos SET model_versions=? WHERE id=?",
                        (db.dumps(live), video_id))

    overlays.clear(video_id, source)
    with db.connect() as con:
        con.execute("DELETE FROM rally_labels WHERE video_id=? AND source=?", (video_id, source))

    # User spot-corrections override the tracker at those frames (clip-local).
    with db.connect() as con:
        corr_rows = con.execute(
            "SELECT frame, x, y FROM ball_corrections WHERE video_id=?", (video_id,)
        ).fetchall()
        trk = con.execute("SELECT payload FROM ball_tracks WHERE video_id=?",
                          (video_id,)).fetchone()
    corrections = {r["frame"]: (r["x"], r["y"]) for r in corr_rows}
    # Dense per-frame ball track from an EXTERNAL tracker (MTI / temporal
    # integration, uploaded via POST /videos/{id}/ball_track). Preferred over
    # the classical detector; manual corrections still win over it. Values are
    # [x, y, diameter|null, confidence] in full-res pixels.
    ext_track = {int(k): v for k, v in db.loads(trk["payload"], {}).items()} if trk else {}
    if ext_track:
        log.info("pass2 %s: using external ball track (%d frames)", video_id, len(ext_track))

    results: list[dict] = []
    total_frames = sum(we - ws + 1 for ws, we, _, _ in windows) or 1
    done_frames = 0

    for wi, (ws, we, raw_ws, raw_we) in enumerate(windows):
        pose = PoseTracker(H)
        fallback = MotionBallDetector(min_area=2.0, max_area=600.0)
        ball_obs: list[tuple[int, float, float, float | None]] = []
        players_by_frame: dict[int, list[tuple[float, float]]] = {}
        player_speed: dict[int, float] = {}     # frame -> mean player speed m/s
        serve_frames: list[int] = []
        prev_courts: dict[int, tuple[float, float]] = {}
        frame_buf: list[np.ndarray] = []
        entries: dict[int, dict] = {}
        last_xy = None

        for f, frame in iter_frames(path, start_frame=ws, end_frame=we + 1):
            obs = pose.update(frame)
            courts = [o.court_xy for o in obs if o.court_xy]
            players_by_frame[f] = courts
            speeds = []
            for o in obs:
                if o.court_xy and o.track_id in prev_courts:
                    px, py = prev_courts[o.track_id]
                    speeds.append(math.hypot(o.court_xy[0] - px, o.court_xy[1] - py) * fps)
            prev_courts = {o.track_id: o.court_xy for o in obs if o.court_xy}
            player_speed[f] = float(np.mean(speeds)) if speeds else 0.0

            if f % max(1, int(fps * 0.5)) == 0 and is_serve_formation(obs):
                serve_frames.append(f)
                pose.assign_numbers_at_serve(obs)

            # ---- ball observation ----------------------------------------
            # Priority: manual correction > external track > TrackNet > classical.
            det = None
            if f in corrections:
                x, y = corrections[f]
                det = (x, y, None, 1.0)
            elif f in ext_track:
                ex = ext_track[f]
                det = (ex[0], ex[1], ex[2], ex[3] if ex[3] is not None else 0.9)
            elif tracknet.available:
                frame_buf.append(frame)
                if len(frame_buf) > 3:
                    frame_buf.pop(0)
                if len(frame_buf) == 3:
                    r = tracknet.infer_triplet(frame_buf)
                    if r:
                        det = r
            else:
                boxes = [o.box for o in obs]
                cands = [cd for cd in fallback.update(frame, boxes)
                         if _in_court_region(H, cd.x, cd.y)]
                c = _pick_candidate(cands, last_xy, max_jump=frame.shape[1] * 0.15)
                if c:
                    det = (c.x, c.y, c.diameter_px, c.score)
            if det:
                ball_obs.append((f, det[0], det[1], det[2]))
                last_xy = (det[0], det[1])

            entries[f] = {
                "f": f,
                "players": [
                    {"id": o.track_id, "num": o.number,
                     "box": [round(v, 1) for v in o.box],
                     "cxy": [round(o.court_xy[0], 2), round(o.court_xy[1], 2)] if o.court_xy else None,
                     "team": o.team,
                     "kp": [[round(x, 1), round(y, 1)] for x, y in o.keypoints]
                           if o.keypoints else None}
                    for o in obs
                ],
                "pspeed": round(player_speed[f], 2),
            }
            if det:
                entries[f]["ball"] = [round(det[0], 1), round(det[1], 1),
                                      round(det[2], 1) if det[2] else None,
                                      round(det[3], 2)]
            done_frames += 1
            if done_frames % 100 == 0:
                # update() also raises if the job was cancelled — keeps a
                # long Pass 2 from blocking the queue after a cancel.
                handle.update(progress=done_frames / total_frames,
                              message=f"Pass 2: window {wi + 1}/{len(windows)}")

        # ---- window-level reasoning ---------------------------------------
        track = smooth_track(ball_obs, max_gap=int(fps * 0.4))
        world = reconstruct_world(track, cam)
        for w in world:  # feature trace: attach reconstruction to entries
            e = entries.get(w.frame)
            if e is not None:
                e["world"] = [round(w.court_x, 2), round(w.court_y, 2),
                              None if math.isnan(w.height) else round(w.height, 3)]
                e["obs"] = w.observed
        events = detect_events(world, players_by_frame, params, fps,
                               model=models.get("rally_end"), entries=entries)
        for ev in events:
            e = entries.get(ev.frame)
            if e is not None:
                e["evt"] = {"kind": ev.kind, "in": ev.in_court, "side": ev.side,
                            "cx": round(ev.court_x, 2), "cy": round(ev.court_y, 2)}

        # A window may contain more than one rally (Pass 1 can under-segment).
        # detect_rallies finds each serve->terminal-end pair; only the last one
        # in a window may lack a terminal event (coarse-gate end below).
        decisions = detect_rallies(events, world, serve_frames, player_speed, params, fps, ws,
                                   start_model=models.get("serve_start"))
        if not decisions:
            # No serve found at all — emit one coarse rally spanning the window
            # (preserves the prior single-rally behaviour for empty windows).
            decisions = [RallyDecision(start_frame=ws, end_frame=None, start_source="coarse_gate")]

        for decision in decisions:
            raw_start = decision.start_frame if decision.start_frame is not None else ws
            end_meta: dict = {"end_event": decision.end_event,
                              "confirmed": decision.confirmed,
                              "notes": list(decision.notes),
                              "start_source": decision.start_source or "coarse_gate"}
            if decision.end_frame is None:
                # No terminal event survived — fall back to the raw coarse-gate
                # window edge and say so honestly in metadata.
                raw_end = raw_we
                end_meta["notes"].append(
                    "no terminal ball event found — end set from coarse gate")
                end_meta["end_source"] = "coarse_gate"
            else:
                raw_end = decision.end_frame
                end_meta["end_source"] = "terminal_event"

            # Record pre-offset (raw) boundaries + clip range so the analytic
            # harness can re-evaluate a candidate offset without re-running CV.
            end_meta.update({"raw_start": raw_start, "raw_end": raw_end,
                             "ws": ws, "we": we,
                             "code_version": DETECTION_CODE_VERSION})

            # Learned systematic corrections (global compounding knobs).
            start = int(np.clip(raw_start + params.get("start_offset_frames", 0), ws, we))
            end = int(np.clip(raw_end + params.get("end_offset_frames", 0), start + 1, we))

            with db.connect() as con:
                con.execute(
                    "INSERT INTO rally_labels (id, video_id, source, start_frame, end_frame, meta)"
                    " VALUES (?,?,?,?,?,?)",
                    (db.new_id(), video_id, source, start, end, db.dumps(end_meta)),
                )
            results.append({"start": start, "end": end, **end_meta})
        overlays.write_entries(video_id, source, list(entries.values()))

    handle.update(progress=1.0, message=f"Pass 2 done: {len(results)} rallies")
    log.info("pass2 %s: %d rallies", video_id, len(results))
    return results
